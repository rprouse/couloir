// Downloads the Material Symbols used as waypoint icons (and a few UI icons,
// such as download) and writes their SVG path data to src/icons/symbolPaths.ts.
// Run it after changing NAMES (and the catalogue in src/icons/waypointIcons.ts):
//
//   node scripts/fetch-material-symbols.mjs
//
// Material Symbols Rounded, FILL 1, wght 400, opsz 24. Apache 2.0.
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const REPO = 'google/material-design-icons'
const COMMIT = '10ecc14790612ca8fd164e3f4ffe9c16fc50d5b7'
const VIEWBOX = '0 -960 960 960'

const NAMES = [
  'arrow_downward', 'backpack', 'cabin', 'camping', 'cell_tower', 'cottage',
  'dangerous', 'delete', 'directions_car', 'download', 'downhill_skiing',
  'edit', 'emergency', 'fence', 'flag', 'hiking', 'landscape', 'landslide', 'local_fire_department', 'local_parking',
  'location_on', 'nordic_walking', 'photo_camera', 'route', 'severe_cold',
  'sledding', 'snowing', 'snowshoeing', 'star', 'visibility', 'warning',
  'water_drop',
]

const OUT = fileURLToPath(new URL('../src/icons/symbolPaths.ts', import.meta.url))

async function fetchPath(name) {
  const url = `https://raw.githubusercontent.com/${REPO}/${COMMIT}/symbols/web/${name}/materialsymbolsrounded/${name}_fill1_24px.svg`
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${name}: HTTP ${res.status} from ${url}`)
  const svg = await res.text()
  if (!svg.includes(`viewBox="${VIEWBOX}"`)) throw new Error(`${name}: unexpected viewBox`)
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)]
  if (paths.length !== 1) throw new Error(`${name}: expected 1 path, found ${paths.length}`)
  return paths[0][1]
}

const sorted = [...NAMES].sort()
const entries = await Promise.all(sorted.map(async (name) => [name, await fetchPath(name)]))

const body = [
  '// GENERATED by scripts/fetch-material-symbols.mjs — do not edit by hand.',
  '// Material Symbols Rounded, FILL 1, wght 400, opsz 24 (Apache 2.0, see',
  `// LICENSE-material-symbols.txt). Source: ${REPO}@${COMMIT}.`,
  `export const SYMBOL_VIEWBOX = '${VIEWBOX}'`,
  '',
  'export const SYMBOL_PATHS = {',
  ...entries.map(([name, d]) => `  ${name}: '${d}',`),
  '} as const satisfies Record<string, string>',
  '',
].join('\n')

await writeFile(OUT, body)
console.log(`Wrote ${entries.length} symbols to ${OUT}`)
